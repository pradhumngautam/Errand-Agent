"""Run every eval scenario offline and write the eval table.

    uv run errand-eval                 # writes evals/RESULTS.md and evals/results.json
    uv run errand-eval -k memory       # only scenarios whose name or category matches

Also run by `pytest` (tests/test_evals.py), so the table is regenerated by the test run.
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
import time
import traceback
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from pathlib import Path

from errand_agent.evals.harness import Harness
from errand_agent.evals.invariants import INVARIANTS, Check, check_all
from errand_agent.evals.scenarios import SCENARIOS, EvalScenario

OUT_DIR = Path("evals")


@dataclass
class Row:
    scenario: str
    category: str
    expected: str
    actual: str
    passed: bool
    notes: str
    checks: list[dict]
    invariants: list[dict]
    model_calls: int
    tool_calls: int
    seconds: float


def run_one(s: EvalScenario, root: Path) -> Row:
    t0 = time.perf_counter()
    h = Harness(root, scenario=s.scenario(), limits=s.limits, context_budget=s.context_budget)
    try:
        result = s.run(h)
        actual, checks = result.actual, result.checks
    except Exception as exc:  # noqa: BLE001 - a crashing scenario is a failed row, not a crashed run
        actual = f"crashed: {type(exc).__name__}: {exc}"
        checks = [Check("scenario ran to completion", False, traceback.format_exc(limit=3))]
    invariants = check_all(h)
    failed = [c for c in checks + invariants if not c.ok]
    notes = "; ".join(f"FAILED {c.name}: {c.detail}" for c in failed) if failed else \
        f"{len(checks)} checks + {len(invariants)} invariants hold"
    return Row(s.name, s.category, s.expected, actual, not failed, notes,
               [asdict(c) for c in checks], [asdict(c) for c in invariants],
               len(h.llm.calls), len(h.events("tool_call")), round(time.perf_counter() - t0, 2))


def run_all(pattern: str | None = None) -> list[Row]:
    selected = [s for s in SCENARIOS if not pattern or pattern in s.name or pattern in s.category]
    rows = []
    with tempfile.TemporaryDirectory(prefix="errand-evals-") as tmp:
        for i, s in enumerate(selected):
            rows.append(run_one(s, Path(tmp) / f"{i:02d}-{s.name}"))
    return rows


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render_markdown(rows: list[Row]) -> str:
    passed = sum(r.passed for r in rows)
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "# Eval results",
        "",
        f"Generated by the test run (`uv run errand-eval` or `uv run pytest`) on {stamp}. Do not edit by hand.",
        "",
        f"**{passed}/{len(rows)} scenarios passed.** Every scenario runs offline against a scripted model "
        "and a seeded mock provider. Each row's checks and the global invariants below are read from ground "
        "truth: the provider's booking table, the agent's approvals and write-ahead log, and the trace files.",
        "",
        "| # | Scenario | Category | Expected | Actual | Result | Notes |",
        "|---|---|---|---|---|---|---|",
    ]
    for i, r in enumerate(rows, 1):
        lines.append(f"| {i} | `{r.scenario}` | {r.category} | {_cell(r.expected)} | {_cell(r.actual)} | "
                     f"{'PASS' if r.passed else '**FAIL**'} | {_cell(r.notes)} |")
    lines += ["", "## Invariants checked after every scenario", ""]
    for inv in INVARIANTS:
        held = sum(1 for r in rows for c in r.invariants if c["name"] == inv.label and c["ok"])
        lines.append(f"- **{inv.label}**: held in {held}/{len(rows)} scenarios. {' '.join((inv.__doc__ or '').split())}")
    lines += ["", "Per-check detail for every scenario is in `evals/results.json`.", ""]
    return "\n".join(lines)


def write(rows: list[Row], out_dir: Path = OUT_DIR) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "RESULTS.md").write_text(render_markdown(rows))
    (out_dir / "results.json").write_text(json.dumps([asdict(r) for r in rows], indent=2, ensure_ascii=False) + "\n")
    return out_dir / "RESULTS.md"


def main() -> None:
    parser = argparse.ArgumentParser(description="Run the offline eval scenarios and write the eval table.")
    parser.add_argument("-k", dest="pattern", help="only scenarios whose name or category contains this")
    parser.add_argument("--out", default=str(OUT_DIR), help="output directory (default: evals)")
    args = parser.parse_args()
    rows = run_all(args.pattern)
    for r in rows:
        print(f"{'PASS' if r.passed else 'FAIL'}  {r.scenario:<38} {r.notes[:110]}")
    if not args.pattern:
        print(f"\nwrote {write(rows, Path(args.out))}")
    passed = sum(r.passed for r in rows)
    print(f"{passed}/{len(rows)} passed")
    sys.exit(0 if passed == len(rows) else 1)


if __name__ == "__main__":
    main()
